SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =====================================================================
-- 一、新建 material_category 表（物资分类表）
--    定义物资大类：办公用品/家具/装饰品/易损易耗/厨房设备/电器电子/布草纺织
-- =====================================================================

DROP TABLE IF EXISTS `material_master`;
DROP TABLE IF EXISTS `material_category`;

CREATE TABLE `material_category` (
  `category_id` int NOT NULL AUTO_INCREMENT COMMENT '分类ID',
  `category_code` varchar(20) NOT NULL COMMENT '分类编码(OFFICE/FURNITURE/DECOR/CONSUMABLE/KITCHEN/ELECTRONIC/LINEN)',
  `category_name` varchar(30) NOT NULL COMMENT '分类名称(办公用品/家具/装饰品/易损易耗/厨房设备/电器电子/布草纺织)',
  `parent_id` int DEFAULT NULL COMMENT '父分类ID(支持二级分类)',
  `level` int DEFAULT 1 COMMENT '分类层级(1=一级,2=二级)',
  `description` varchar(200) DEFAULT NULL COMMENT '分类说明',
  `sort_order` int DEFAULT 0 COMMENT '排序号',
  `status` varchar(10) DEFAULT 'active' COMMENT '状态(active/inactive)',
  `created_at` timestamp DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`category_id`),
  UNIQUE KEY `uk_category_code` (`category_code`),
  KEY `idx_parent` (`parent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='物资分类表';

-- =====================================================================
-- 二、新建 material_master 表（物资主表）
--    核心约束：material_name 全局唯一（不可能有两个名称）
--    每个物资关联到一个分类，含规格/单位/参考单价等
-- =====================================================================

CREATE TABLE `material_master` (
  `material_id` int NOT NULL AUTO_INCREMENT COMMENT '物资ID',
  `material_code` varchar(30) NOT NULL COMMENT '物资编码(WZ-分类缩写-序号)',
  `material_name` varchar(100) NOT NULL COMMENT '物资名称(全局唯一)',
  `category_id` int NOT NULL COMMENT '分类ID(→material_category)',
  `spec` varchar(100) DEFAULT NULL COMMENT '规格型号',
  `unit` varchar(20) DEFAULT NULL COMMENT '计量单位(个/套/把/台/卷/箱/包/件/块/条)',
  `reference_price` decimal(10,2) DEFAULT NULL COMMENT '参考单价',
  `min_stock` decimal(10,2) DEFAULT NULL COMMENT '最低库存预警',
  `max_stock` decimal(10,2) DEFAULT NULL COMMENT '最高库存上限',
  `brand` varchar(50) DEFAULT NULL COMMENT '品牌',
  `supplier_id` int DEFAULT NULL COMMENT '首选供应商ID(→supplier_master)',
  `is_consumable` tinyint DEFAULT 0 COMMENT '是否易耗品(0=耐用品,1=易耗品)',
  `lifecycle_days` int DEFAULT NULL COMMENT '预计使用寿命(天,易耗品为预计用量天数)',
  `storage_location` varchar(100) DEFAULT NULL COMMENT '默认存放位置',
  `remark` varchar(255) DEFAULT NULL COMMENT '备注',
  `status` varchar(10) DEFAULT 'active' COMMENT '状态(active/inactive)',
  `sort_order` int DEFAULT 0 COMMENT '排序号',
  `created_at` timestamp DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`material_id`),
  UNIQUE KEY `uk_material_code` (`material_code`),
  UNIQUE KEY `uk_material_name` (`material_name`),
  KEY `idx_category` (`category_id`),
  KEY `idx_supplier` (`supplier_id`),
  KEY `idx_consumable` (`is_consumable`),
  CONSTRAINT `fk_material_category` FOREIGN KEY (`category_id`) REFERENCES `material_category` (`category_id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='物资主表(名称全局唯一)';

SET FOREIGN_KEY_CHECKS = 1;

