CREATE TABLE IF NOT EXISTS post (
  post_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  store_id BIGINT NOT NULL DEFAULT 1,
  dept_id INT NOT NULL,
  post_name VARCHAR(64) NOT NULL,
  post_code VARCHAR(64) NOT NULL,
  headcount INT NOT NULL DEFAULT 0,
  on_duty_count INT NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  remark VARCHAR(255) NULL,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_post_store_code (store_id, post_code),
  KEY idx_post_dept (dept_id),
  CONSTRAINT fk_post_department FOREIGN KEY (dept_id) REFERENCES department(dept_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS contract (
  contract_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  store_id BIGINT NOT NULL,
  staff_id INT NOT NULL,
  contract_no VARCHAR(50) NOT NULL,
  contract_type TINYINT NOT NULL DEFAULT 1,
  sign_date DATE NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NULL,
  file_path VARCHAR(500) NULL,
  status TINYINT NOT NULL DEFAULT 1,
  remark VARCHAR(255) NULL,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_contract_no (contract_no),
  KEY idx_contract_staff (staff_id),
  CONSTRAINT fk_contract_staff FOREIGN KEY (staff_id) REFERENCES staff_master(staff_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
