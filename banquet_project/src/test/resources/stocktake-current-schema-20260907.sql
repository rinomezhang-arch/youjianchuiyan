  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`detail_id`),
  KEY `idx_diff_type` (`diff_type`),
  KEY `idx_ingredient_id` (`ingredient_id`),
  KEY `idx_store_id` (`store_id`),
  KEY `idx_take_id` (`take_id`),
  KEY `fk_stock_take_detail_ingredient_id` (`ingredient_id`,`store_id`),
  CONSTRAINT `fk_stock_take_detail_ingredient_id` FOREIGN KEY (`ingredient_id`, `store_id`) REFERENCES `ingredient_master` (`ingredient_id`, `store_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fk_stock_take_detail_take_id` FOREIGN KEY (`take_id`) REFERENCES `stock_take` (`take_id`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='盘点明细表';
